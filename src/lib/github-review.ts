import type { Octokit } from '@octokit/rest';
import type { PRReviewResult, ReviewComment } from './reviewer';

/**
 * Result returned after successfully creating a GitHub Pull Request Review.
 */
export interface PostReviewResult {
  id: number;
  htmlUrl: string;
  event: 'APPROVE' | 'REQUEST_CHANGES' | 'COMMENT';
  commentsCount: number;
}

/**
 * Parameters for posting a review to GitHub.
 */
export interface PostPullRequestReviewParams {
  octokit: Octokit;
  owner: string;
  repo: string;
  pullNumber: number;
  commitSha: string;
  review: PRReviewResult;
}

/**
 * Formats an individual line review comment with badge header and optional GitHub suggestion.
 */
export function formatReviewCommentBody(comment: ReviewComment): string {
  const badge = `**[${comment.severity.toUpperCase()} | ${comment.category.toUpperCase()}]**`;
  let body = `${badge}\n${comment.comment.trim()}`;

  if (comment.suggestedCode && comment.suggestedCode.trim().length > 0) {
    let codeSnippet = comment.suggestedCode.trim();
    // Strip redundant markdown fence wraps if already generated by LLM
    if (codeSnippet.startsWith('```')) {
      codeSnippet = codeSnippet
        .replace(/^```(?:suggestion|[a-zA-Z0-9_-]*)\r?\n?/, '')
        .replace(/\r?\n?```$/, '')
        .trim();
    }

    body += `\n\n\`\`\`suggestion\n${codeSnippet}\n\`\`\``;
  }

  return body;
}

/**
 * Formats the top-level Pull Request review summary body.
 */
export function formatReviewSummaryBody(
  result: PRReviewResult,
  totalCommentsPosted: number
): string {
  const findingsNote =
    totalCommentsPosted > 0
      ? `> ⚠️ **${totalCommentsPosted} inline finding${totalCommentsPosted === 1 ? '' : 's'} flagged** across the pull request.`
      : `> ✅ **No issues found.** All analyzed changes look solid!`;

  const recommendationBadge = `**Recommendation:** \`${result.approvalRecommendation}\``;

  return [
    `## VigilPR Review`,
    recommendationBadge,
    '',
    result.summary.trim(),
    '',
    findingsNote,
    '',
    `---`,
    `*Generated by [VigilPR](https://github.com) • AI-powered Pull Request review and security audit bot*`,
  ].join('\n');
}

/**
 * Formats and posts a single batched Pull Request review back to GitHub via octokit.rest.pulls.createReview.
 */
export async function postPullRequestReview(
  params: PostPullRequestReviewParams
): Promise<PostReviewResult> {
  const { octokit, owner, repo, pullNumber, commitSha, review } = params;

  // 1. Map validated comments into GitHub's expected inline review comment format
  const formattedComments = review.comments.map((c) => ({
    path: c.path,
    line: c.line,
    side: 'RIGHT' as const,
    body: formatReviewCommentBody(c),
  }));

  // 2. Format the top-level review body
  const summaryBody = formatReviewSummaryBody(review, formattedComments.length);

  // 3. Determine GitHub review event
  let eventToUse: 'APPROVE' | 'REQUEST_CHANGES' | 'COMMENT' =
    review.approvalRecommendation;

  // If recommendation is REQUEST_CHANGES but 0 inline comments exist, fallback to COMMENT
  if (eventToUse === 'REQUEST_CHANGES' && formattedComments.length === 0) {
    console.warn(
      '[VigilPR] approvalRecommendation is REQUEST_CHANGES but 0 inline comments exist. Falling back to COMMENT.'
    );
    eventToUse = 'COMMENT';
  }

  // 4. Post the review with 422 fallback guard for self-reviews or restricted permissions
  try {
    const { data } = await octokit.rest.pulls.createReview({
      owner,
      repo,
      pull_number: pullNumber,
      commit_id: commitSha,
      body: summaryBody,
      event: eventToUse,
      comments: formattedComments,
    });

    return {
      id: data.id,
      htmlUrl: data.html_url,
      event: eventToUse,
      commentsCount: formattedComments.length,
    };
  } catch (error: unknown) {
    const httpStatus =
      error && typeof error === 'object' && 'status' in error
        ? (error as { status: number }).status
        : undefined;

    // Retry once with 'COMMENT' if GitHub rejects APPROVE/REQUEST_CHANGES (e.g., self-review restriction)
    if (httpStatus === 422 && eventToUse !== 'COMMENT') {
      console.warn(
        `[VigilPR] GitHub API returned 422 for event "${eventToUse}" (likely self-review or branch permission restriction). Retrying with event: "COMMENT"...`
      );

      const { data } = await octokit.rest.pulls.createReview({
        owner,
        repo,
        pull_number: pullNumber,
        commit_id: commitSha,
        body: summaryBody,
        event: 'COMMENT',
        comments: formattedComments,
      });

      return {
        id: data.id,
        htmlUrl: data.html_url,
        event: 'COMMENT',
        commentsCount: formattedComments.length,
      };
    }

    console.error('[VigilPR] Failed to post GitHub review:', error);
    throw error;
  }
}
